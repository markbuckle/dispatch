import { writeFile } from 'node:fs/promises';
import { dirname, join } from 'node:path';
import { fileURLToPath } from 'node:url';

const API_URL = 'https://www.caniemail.com/api/data.json';
const LICENSE_URL = 'https://raw.githubusercontent.com/hteumeuleu/caniemail/main/LICENSE';

// the engine checks these four, so vendoring all 308 features would put 657 KB of unreviewable JSON in the diff
const SLUGS = ['css-display-flex', 'css-display-grid', 'css-variables', 'css-position'];

const outDir = join(dirname(fileURLToPath(import.meta.url)), '..', 'src', 'data');

async function get(url) {
  const response = await fetch(url);
  if (!response.ok) throw new Error(`${url} responded ${response.status}`);
  return response;
}

// caniemail authors version keys chronologically rather than sortably, so 16.80 precedes 2011 by insertion
function latestTested(versions) {
  const keys = Object.keys(versions);
  const version = keys[keys.length - 1];
  return version === undefined ? undefined : { version, raw: String(versions[version]) };
}

// a code carries its note references inline, as in "a #1 #2"
function splitCode(raw) {
  const [code, ...refs] = raw.trim().split(/\s+/);
  return { code, refs: refs.map((ref) => ref.replace('#', '')) };
}

function levelOf(code) {
  if (code === 'n') return 'unsupported';
  if (code === 'a') return 'partial';
  return undefined;
}

const upstream = await (await get(API_URL)).json();
const license = await (await get(LICENSE_URL)).text();
const { family: familyNames, platform: platformNames } = upstream.nicenames;

function resolve(feature) {
  const clients = [];
  let supported = 0;
  let total = 0;

  for (const [familyKey, platforms] of Object.entries(feature.stats)) {
    for (const [platformKey, versions] of Object.entries(platforms)) {
      const tested = latestTested(versions);
      if (!tested) continue;

      const { code, refs } = splitCode(tested.raw);
      total += 1;
      if (code === 'y' || code === 'a') supported += 1;

      const level = levelOf(code);
      if (!level) continue;

      const notes = refs.map((ref) => feature.notes_by_num?.[ref]).filter(Boolean);

      clients.push({
        family: familyNames[familyKey] ?? familyKey,
        platform: platformNames[platformKey] ?? platformKey,
        version: tested.version,
        level,
        note: notes.length > 0 ? notes.join(' ') : null,
      });
    }
  }

  clients.sort(
    (a, b) =>
      Number(a.level === 'partial') - Number(b.level === 'partial') ||
      a.family.localeCompare(b.family) ||
      a.platform.localeCompare(b.platform),
  );

  return {
    slug: feature.slug,
    title: feature.title,
    url: feature.url,
    last_test_date: feature.last_test_date,
    // matches the percentage caniemail prints on each feature page, where a partial still counts as supported
    support_score: total === 0 ? 0 : Number(((supported / total) * 100).toFixed(2)),
    clients,
  };
}

const features = SLUGS.map((slug) => {
  const feature = upstream.data.find((entry) => entry.slug === slug);
  if (!feature) throw new Error(`upstream no longer publishes ${slug}`);
  return resolve(feature);
});

const retrievedAt = new Date().toISOString().slice(0, 10);

const snapshot = {
  source: {
    url: API_URL,
    project: 'Can I email... (github.com/hteumeuleu/caniemail)',
    api_version: upstream.api_version,
    last_update_date: upstream.last_update_date,
    retrieved_at: retrievedAt,
  },
  features,
};

await writeFile(join(outDir, 'caniemail.json'), `${JSON.stringify(snapshot, null, 2)}\n`);
await writeFile(join(outDir, 'LICENSE'), license);

const rows = features
  .map(
    (f) =>
      `| \`${f.slug}\` | ${f.title} | ${f.last_test_date} | ${f.support_score}% | ${f.clients.length} |`,
  )
  .join('\n');

const provenance = `# Provenance - the caniemail snapshot

Generated by \`scripts/vendor-caniemail.mjs\`. Do not edit \`caniemail.json\` or this
file by hand, re-run the script instead:

\`\`\`
pnpm --filter @dispatch/compat vendor:caniemail
\`\`\`

## Where it came from

| What | Value |
|---|---|
| Source | \`${API_URL}\` |
| Project | Can I email... by Rémi Parmentier, \`github.com/hteumeuleu/caniemail\` |
| Licence | MIT, see \`LICENSE\` in this directory |
| Upstream \`api_version\` | ${upstream.api_version} |
| Upstream \`last_update_date\` | ${upstream.last_update_date} |
| Retrieved | ${retrievedAt} |
| Features taken | ${SLUGS.length} of ${upstream.data.length} |

## What the script changes

Upstream nests support as \`stats[family][platform][version]\`, with codes like
\`"a #1"\` and note text held separately. The script flattens that to the one
question the engine asks: on the newest version caniemail has tested, which
clients handle this badly. It resolves the display names, resolves the note
references into text, and computes the support score. So this file is derived
from caniemail, not a verbatim copy of it, and the resolving logic lives in the
script rather than at import time.

## Two different dates, two different claims

\`last_update_date\` is when the caniemail dataset last changed. Each feature also
carries its own \`last_test_date\`, which is when that feature was last run against
real clients. They diverge by years, and a finding is only as fresh as the second
one.

| Slug | Feature | Last tested | Support score | Clients flagged |
|---|---|---|---|---|
${rows}

Individual client rows can be newer than the feature's own test date, because
caniemail amends single entries without re-running the whole test.

## Why a snapshot rather than a fetch

A compatibility check runs on every keystroke in a template editor and has to give
the same answer twice. Fetching at runtime would put a third-party outage in that
path and make a warning appear or vanish without the template changing.
`;

await writeFile(join(outDir, 'PROVENANCE.md'), provenance);

console.log(`api_version ${upstream.api_version}, updated ${upstream.last_update_date}`);
for (const f of features) {
  console.log(
    `  ${f.slug.padEnd(20)} ${String(f.support_score).padStart(6)}%  ${String(f.clients.length).padStart(2)} clients  tested ${f.last_test_date}`,
  );
}
